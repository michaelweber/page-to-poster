"""Regenerate docs/kit-reference.md from the docstrings of mapkit/blender/kit.py and the material table.

    python tools/kit_reference.py

Run it after changing kit.py or materials.py. It reads the source text only, so it needs neither Blender nor bpy.
"""
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KIT = ROOT / "mapkit" / "blender" / "kit.py"
MATERIALS = ROOT / "mapkit" / "blender" / "materials.py"
OUT = ROOT / "docs" / "kit-reference.md"

# section banner in kit.py -> heading and lead-in here; sections not listed are the builder's own and left out
SECTIONS = {
    "ready-made props": ("Ready-made props", "Whole objects. Each takes the mesh builder first; those with `M` are "
                         "placed by a transform `T(x, y, z, rz=angle)`, the others by `x, y`."),
    "decals & lights": ("Decals and lights", "Decals are ink stickers from the project's `decals/` folder."),
    "basics": ("Basics", "The mesh builder, transforms, named features and your own materials."),
    "primitives": ("Primitives", "Closed solids to build anything the ready-made props do not cover. `mat` is a "
                   "material name; `M` is an optional transform."),
    "path utils": ("Paths", "Helpers for polylines of (x, y) points: conveyor lines, pipes along a wall, trails."),
}
ORDER = ("ready-made props", "decals & lights", "basics", "primitives", "path utils")
SKIP = {"init", "coll", "MAT", "panel_rects", "rest_z"}


def cell(text):
    return " ".join(text.split()).replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")


def signature(node):
    return f"{node.name}({ast.unparse(node.args)})".replace("|", "\\|")


def kit_sections():
    src = KIT.read_text(encoding="utf-8")
    banners = [(i + 1, line.strip("# =").strip()) for i, line in enumerate(src.splitlines()) if line.startswith("# ====")]
    out = {name: [] for name in SECTIONS}
    classes = []
    for node in ast.parse(src).body:
        section = next((name for line, name in reversed(banners) if line <= node.lineno), None)
        if isinstance(node, ast.ClassDef):
            classes.append(node)
        elif (isinstance(node, ast.FunctionDef) and section in out and not node.name.startswith("_")
              and node.name not in SKIP):
            out[section].append((signature(node), ast.get_docstring(node) or ""))
    return out, classes


def materials():
    tree = ast.parse(MATERIALS.read_text(encoding="utf-8"))
    table = next(n.value for n in tree.body if isinstance(n, ast.Assign) and n.targets[0].id == "MATS")
    for key, call in zip(table.keys, table.values):
        spec = {kw.arg: ast.literal_eval(kw.value) for kw in call.keywords}
        r, g, b = spec["color"]
        lum = 0.299 * r + 0.587 * g + 0.114 * b
        if r > 1.7 * g and r > 1.7 * b:
            prints = "accent ink"
        elif spec.get("emit", 0) > 1:
            prints = "white (glows)"
        elif lum > 0.7:
            prints = "white where lit"
        elif lum < 0.2:
            prints = "solid ink"
        else:
            prints = "stippled paper where lit, ink in shade"
        yield key.value, spec.get("tex") or "(flat color)", prints


def main():
    sections, classes = kit_sections()
    lines = ["# Kit reference", "",
             "Generated by `python tools/kit_reference.py` from the docstrings in `mapkit/blender/kit.py`. "
             "[props.md](props.md) explains how to use these; the picture there shows every ready-made prop.", "",
             "Units are meters, +x is east, +y is north, the floor is z = 0, and angles are radians "
             "(`math.radians(90)` or `math.pi / 2`). `from mapkit.blender.kit import *` also gives a props module "
             "`math`, `random`, and the light colors `WARM` and `RED`.", ""]
    for name in ORDER:
        title, lead = SECTIONS[name]
        lines += [f"## {title}", "", lead, "", "| Call | What it makes |", "|---|---|"]
        lines += [f"| `{sig}` | {cell(doc)} |" for sig, doc in sections[name]]
        lines.append("")
        if name == "basics":
            for cls in classes:
                lines += [f"### `{cls.name}`", "", cell(ast.get_docstring(cls) or ""), "",
                          "| Method | What it does |", "|---|---|"]
                lines += [f"| `{signature(m)}` | {cell(ast.get_docstring(m) or '')} |" for m in cls.body
                          if isinstance(m, ast.FunctionDef) and not m.name.startswith("_") and ast.get_docstring(m)]
                lines.append("")
    lines += ["## Materials", "",
              "Pass these names as `mat`. The last column is how a surface usually prints on the poster; light and "
              "shadow in the render shift it. Register more with `material(name, color, tex=...)`.", "",
              "| Name | Texture | On the poster |", "|---|---|---|"]
    lines += [f"| `{name}` | {tex} | {prints} |" for name, tex, prints in materials()]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("+", OUT)


if __name__ == "__main__":
    main()
